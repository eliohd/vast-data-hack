"""Writes server/fixtures/rideahead/snapshots.json — sample SessionSnapshots for the web lane,
produced by running the real runtime on the fixture scenario with recorded openrouteservice
responses (no network; routes labelled cached_provider).

uv run python -m app.export_fixtures      (also run by `make gen-api`)
"""

from __future__ import annotations

import asyncio
import json

from pydantic import SecretStr

from app.config import Settings
from app.services import Services

SAMPLE_TIMES = (0, 60, 200, 330, 450, 600)


async def build() -> dict[str, dict]:
    settings = Settings(
        tracing=False,
        rideahead_routing="ors",  # no key → recorded genuine ORS responses (cached_provider)
        rideahead_perception="fixture",
        ors_api_key=SecretStr(""),
    )
    services = Services.create(settings)
    try:
        rt = services.rideahead
        snap = await rt.create_session()
        out: dict[str, dict] = {}
        for t in SAMPLE_TIMES:
            snap = await rt.advance(snap.session_id, t)
            data = snap.model_dump(mode="json")
            data["session_id"] = "fixture-session"
            out[f"t{t}"] = data
        return out
    finally:
        await services.close()


def main() -> None:
    settings = Settings(tracing=False)
    path = settings.rideahead_fixtures / "snapshots.json"
    snapshots = asyncio.run(build())
    payload = {"_note": "Generated by app.export_fixtures from the FIXTURE scenario.", **snapshots}
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
